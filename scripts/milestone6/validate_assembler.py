#!/usr/bin/env python3
"""
scripts/milestone6/validate_assembler.py

Independent validation of Aeon R2 instruction encodings generated by
scripts/milestone5/aeon_r2_mini_assembler.py.

Validation approach:
  - Parses instruction bitfields strictly according to the SLEIGH specification
    in ghidra-aeon/data/languages/aeon.slaspec and aeon_ORBIS32.sinc.
  - Compares assembler-generated machine code against independent bitfield
    reconstructions.
  - Verifies effective memory address offsets, register indices, and immediates.
"""

import sys
import os

# Add milestone5 path to import assembler
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../milestone5')))
from aeon_r2_mini_assembler import AeonR2Assembler

class IndependentSLEIGHDecoder:
    """
    Independent decoder implementing the exact SLEIGH specification rules from
    aeon_ORBIS32.sinc and aeon.slaspec without sharing code with milestone5 decoder.
    """
    @staticmethod
    def decode(data, offset=0):
        if offset >= len(data):
            return None
        
        b0 = data[offset]
        prefix = (b0 >> 5) & 0x07

        # 16-bit instructions (i16_decoder = 4)
        if prefix == 4:
            if offset + 2 > len(data): return None
            val = (data[offset] << 8) | data[offset + 1]
            opcode = (val >> 10) & 0x3F
            rD = (val >> 5) & 0x1F
            rA = val & 0x1F
            simm5 = val & 0x1F
            if simm5 & 0x10: simm5 -= 0x20
            uimm = val & 0x1F

            if opcode == 0x20:
                bit5 = (val >> 5) & 1
                bit0 = val & 1
                imm4 = (val >> 1) & 0x0F
                if bit5 == 0 and bit0 == 1:
                    return 2, "bt.nop", {"imm": imm4}, f"bt.nop 0x{imm4:x}"
            elif opcode == 0x21:
                if uimm == 0x09:
                    return 2, "bt.jr", {"rD": rD}, f"bt.jr r{rD}" + (" (ret)" if rD == 9 else "")
            elif opcode == 0x22:
                return 2, "bt.mov", {"rD": rD, "rA": rA}, f"bt.mov r{rD}, r{rA}"
            elif opcode == 0x23:
                return 2, "bt.add", {"rD": rD, "rA": rA}, f"bt.add r{rD}, r{rA}"
            elif opcode == 0x26:
                return 2, "bt.movi", {"rD": rD, "simm": simm5}, f"bt.movi r{rD}, {simm5}"
            elif opcode == 0x27:
                return 2, "bt.addi", {"rD": rD, "simm": simm5}, f"bt.addi r{rD}, {simm5}"

            return 2, "bt.unknown", {"opcode": opcode}, f"bt.op_0x{opcode:02x}"

        # 24-bit instructions (i24_decoder = 0..3)
        elif prefix < 4:
            if offset + 3 > len(data): return None
            val = (data[offset] << 16) | (data[offset + 1] << 8) | data[offset + 2]
            opcode = (val >> 18) & 0x3F
            rD = (val >> 13) & 0x1F
            rA = (val >> 8) & 0x1F
            rB = (val >> 3) & 0x1F
            uimm0_2 = val & 0x03

            if opcode == 0x03:
                if uimm0_2 == 0:
                    # bn.sw: i24_simm0_8 & i24_rA (word-aligned offset)
                    simm8 = val & 0xFF
                    if simm8 & 0x80: simm8 -= 0x100
                    return 3, "bn.sw", {"rD": rD, "rA": rA, "offset": simm8}, f"bn.sw {simm8}(r{rA}), r{rD}"
                elif uimm0_2 == 2:
                    # bn.lwz: i24_simm2_6 << 2
                    # Bits [7:2] are simm2_6
                    simm2_6 = (val >> 2) & 0x3F
                    if simm2_6 & 0x20: simm2_6 -= 0x40
                    eff_offset = simm2_6 << 2
                    return 3, "bn.lwz", {"rD": rD, "rA": rA, "offset": eff_offset}, f"bn.lwz r{rD}, {eff_offset}(r{rA})"
            elif opcode == 0x07:
                simm8 = val & 0xFF
                if simm8 & 0x80: simm8 -= 0x100
                return 3, "bn.addi", {"rD": rD, "rA": rA, "simm": simm8}, f"bn.addi r{rD}, r{rA}, {simm8}"
            elif opcode == 0x10:
                uimm0_3 = val & 0x07
                alu_names = ["divs", "divu", "mulu", "muls", "add", "sub", "subb", "addc"]
                return 3, f"bn.{alu_names[uimm0_3]}", {"rD": rD, "rA": rA, "rB": rB}, f"bn.{alu_names[uimm0_3]} r{rD}, r{rA}, r{rB}"
            elif opcode == 0x14:
                ik = val & 0xFF
                return 3, "bn.ori", {"rD": rD, "rA": rA, "imm": ik}, f"bn.ori r{rD}, r{rA}, 0x{ik:x}"

            return 3, "bn.unknown", {"opcode": opcode}, f"bn.op_0x{opcode:02x}"

        # 32-bit instructions (i32_decoder = 5..7)
        else:
            if offset + 4 > len(data): return None
            val = (data[offset] << 24) | (data[offset + 1] << 16) | (data[offset + 2] << 8) | data[offset + 3]
            opcode = (val >> 26) & 0x3F
            rD = (val >> 21) & 0x1F
            rA = (val >> 16) & 0x1F
            simm16 = val & 0xFFFF
            if simm16 & 0x8000: simm16 -= 0x10000
            uimm16 = val & 0xFFFF

            if opcode == 0x3F:
                return 4, "bg.addi", {"rD": rD, "rA": rA, "simm": simm16}, f"bg.addi r{rD}, r{rA}, {simm16}"
            elif opcode == 0x30:
                bit0 = val & 1
                uimm1_3 = (val >> 1) & 0x07
                imm16 = (val >> 5) & 0xFFFF
                if bit0 == 1 and uimm1_3 == 0:
                    return 4, "bg.movhi", {"rD": rD, "imm": imm16}, f"bg.movhi r{rD}, 0x{imm16:04x}"
            elif opcode == 0x32:
                return 4, "bg.ori", {"rD": rD, "rA": rA, "imm": uimm16}, f"bg.ori r{rD}, r{rA}, 0x{uimm16:04x}"

            return 4, "bg.unknown", {"opcode": opcode}, f"bg.op_0x{opcode:02x}"

def main():
    print("==================================================================")
    print(" Milestone 6: Independent Aeon R2 Assembler Validation            ")
    print("==================================================================")

    asm = AeonR2Assembler()
    decoder = IndependentSLEIGHDecoder()

    # Reconstruct the 31-byte program from milestone 5
    test_program = [
        ("bg.addi r1, r1, -16", asm.bg_addi(1, 1, -16), 4, "bg.addi", {"rD": 1, "rA": 1, "simm": -16}),
        ("bn.sw 12(r1), r9",    asm.bn_sw(12, 1, 9),    3, "bn.sw",   {"rD": 9, "rA": 1, "offset": 12}),
        ("bn.sw 8(r1), r10",    asm.bn_sw(8, 1, 10),    3, "bn.sw",   {"rD": 10, "rA": 1, "offset": 8}),
        ("bt.movi r10, 10",     asm.bt_movi(10, 10),    2, "bt.movi", {"rD": 10, "simm": 10}),
        ("bt.add r3, r4",       asm.bt_add(3, 4),       2, "bt.add",  {"rD": 3, "rA": 4}),
        ("bt.add r3, r10",      asm.bt_add(3, 10),      2, "bt.add",  {"rD": 3, "rA": 10}),
        ("bn.addi r3, r3, 5",   asm.bn_addi(3, 3, 5),   3, "bn.addi", {"rD": 3, "rA": 3, "simm": 5}),
        ("bn.lwz r10, 8(r1)",   asm.bn_lwz(10, 8, 1),   3, "bn.lwz",  {"rD": 10, "rA": 1, "offset": 8}),
        ("bn.lwz r9, 12(r1)",   asm.bn_lwz(9, 12, 1),   3, "bn.lwz",  {"rD": 9, "rA": 1, "offset": 12}),
        ("bg.addi r1, r1, 16",  asm.bg_addi(1, 1, 16),  4, "bg.addi", {"rD": 1, "rA": 1, "simm": 16}),
        ("bt.jr r9",            asm.bt_jr(9),           2, "bt.jr",   {"rD": 9}),
    ]

    assembled_bytes = bytearray()
    for name, b, exp_len, exp_mnem, exp_fields in test_program:
        assembled_bytes.extend(b)

    print(f"Total Assembled Machine Code: {len(assembled_bytes)} bytes\n")
    print(f"{'Idx':3s} | {'Raw Hex':12s} | {'Exp Mnemonic':18s} | {'Independent Decode':24s} | {'Status'}")
    print("-" * 75)

    all_valid = True
    offset = 0
    idx = 1
    for name, b, exp_len, exp_mnem, exp_fields in test_program:
        res = decoder.decode(assembled_bytes, offset)
        if res is None:
            print(f"{idx:02d}  | {b.hex():12s} | {name:18s} | DECODE_FAILED            | [FAIL]")
            all_valid = False
            break

        length, mnem, fields, disasm = res
        hex_str = b.hex()
        status = "[PASS]" if (length == exp_len and mnem == exp_mnem and fields == exp_fields) else "[MISMATCH]"
        if status == "[MISMATCH]":
            all_valid = False

        print(f"{idx:02d}  | {hex_str:12s} | {name:18s} | {disasm:24s} | {status}")
        offset += length
        idx += 1

    print("-" * 75)
    print(f"Independent Validation Result: {'ALL INSTRUCTIONS VALIDATED' if all_valid else 'VALIDATION FAILED'}")

    return 0 if all_valid else 1

if __name__ == "__main__":
    sys.exit(main())
